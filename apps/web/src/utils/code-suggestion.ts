export function suggestCodeFromName(name: string, maxLength = 80): string {
  const source = name.normalize('NFKC').trim();
  if (!source) return '';
  const tokens: string[] = [];
  let latin = '';
  let cjk = '';
  const flushLatin = () => { if (latin) { tokens.push(latin.toUpperCase()); latin = ''; } };
  const flushCjk = () => { if (cjk) { tokens.push(cjk); cjk = ''; } };
  for (const char of source) {
    if (/^[A-Za-z0-9]$/.test(char)) {
      flushCjk(); latin += char;
      continue;
    }
    if (initials[char]) {
      flushLatin(); cjk += initials[char];
      continue;
    }
    flushLatin(); flushCjk();
    if (/\s|[-_.:/\\]/.test(char)) continue;
    // Unknown characters get an explicit Unicode marker rather than silently
    // producing an unrelated code. The suggestion remains editable.
    if (/\p{Script=Han}/u.test(char)) tokens.push(`U${char.codePointAt(0)?.toString(16).toUpperCase() ?? ''}`);
  }
  flushLatin(); flushCjk();
  let result = tokens.filter(Boolean).join('_').replace(/_+/g, '_').replace(/^_+|_+$/g, '');
  if (!result) result = 'CUSTOM';
  if (!/^[A-Z]/.test(result)) result = `X_${result}`;
  const limit = Math.max(2, Math.floor(maxLength) || 80);
  result = result.slice(0, limit).replace(/_+$/g, '');
  if (result.length < 2) result = `${result}X`.slice(0, limit);
  return result;
}
