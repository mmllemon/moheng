import { chromium } from 'playwright-core';
const b=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const c=await b.newContext({viewport:{width:1440,height:900},locale:'zh-CN'});
const p=await c.newPage();
await p.goto('http://localhost:5173/login',{waitUntil:'networkidle'});
await p.locator('input[type=email]').first().fill('admin@local.test');
await p.locator('input[type=password]').first().fill('ChangeMe123!');
await p.locator('button[type=submit]').first().click();
await p.waitForTimeout(2600);
await p.evaluate(()=>{history.pushState(null,'','/cost/changes');dispatchEvent(new PopStateEvent('popstate'))});
await p.waitForTimeout(1400);
console.log('=== 页面所有按钮 ===');
const btns=await p.evaluate(()=>[...document.querySelectorAll('button')].map(e=>({t:(e.textContent||'').trim().slice(0,14),d:e.disabled})));
console.log(JSON.stringify(btns));
console.log('\n=== 表格行数 ===');
console.log(await p.evaluate(()=>document.querySelectorAll('tbody tr').length));
// 点 进入审核
await p.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(e=>(e.textContent||'').includes('进入审核'));if(b)b.click()});
await p.waitForTimeout(1200);
console.log('\n=== 点后是否有 dialog ===');
console.log(await p.evaluate(()=>{const d=document.querySelector('.dialog, .modal, [role=dialog]');return d?d.className+' | inputs:'+d.querySelectorAll('input').length:'无弹窗'}));
console.log('\n=== 全部输入框 ===');
console.log(await p.evaluate(()=>[...document.querySelectorAll('input')].map(e=>({type:e.type,ro:e.readOnly,dis:e.disabled,ph:e.placeholder||'',v:(e.value||'').slice(0,12),inDialog:!!e.closest('.dialog,.modal')}))));
await b.close();
